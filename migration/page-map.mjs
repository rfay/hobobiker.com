#!/usr/bin/env node
// Writes PAGE-MAP.md: every page of the site with links to the same path on the original, the static archive
// (Part 2) and the Drupal 11 rebuild (Part 3), for comparing them by eye. Nodes by nid (from data/manifest.json,
// published or not), then every other page the suite checks (baseline/semantic/index.json).
//
//   node migration/page-map.mjs                 # the Coder URLs (public during the sessions only)
//   node migration/page-map.mjs --local         # the local DDEV URLs, for working in this workspace
//   node migration/page-map.mjs --original URL --static URL --d11 URL --out FILE

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const arg = (name, dflt) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : dflt);
const local = argv.includes('--local');
const hosts = {
  original: arg('--original', local ? 'https://hobobiker-copy.ddev.site' : 'https://hobobiker-copy--remotework--rfay.coder.ddev.com'),
  // The static project (the same files as static.hobobiker.com), served with its nginx rule, so ?page=N works.
  static: arg('--static', local ? 'https://hobobiker-static.ddev.site' : 'https://hobobiker-static--remotework--rfay.coder.ddev.com'),
  d11: arg('--d11', local ? 'https://hobobiker-d11.ddev.site' : 'https://hobobiker-d11--remotework--rfay.coder.ddev.com'),
};
const out = path.resolve(arg('--out', path.join(repo, 'PAGE-MAP.md')));

const tp = path.join(repo, 'test', 'playwright');
const manifest = JSON.parse(readFileSync(path.join(tp, 'data', 'manifest.json'), 'utf8'));
const index = JSON.parse(readFileSync(path.join(tp, 'baseline', 'semantic', 'index.json'), 'utf8'));

// One cell with the three links. Paths keep their query (?page=N); spaces and the like are encoded.
const url = (host, p) => `${host}/${encodeURI(p).replace(/\(/g, '%28').replace(/\)/g, '%29')}`;
const links = (p) => `[original](${url(hosts.original, p)}) · [static](${url(hosts.static, p)}) · [Drupal 11](${url(hosts.d11, p)})`;
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

const lines = [
  '# Page map: the original, the static archive, the Drupal 11 rebuild',
  '',
  `Generated by \`migration/page-map.mjs\`${local ? ' --local' : ''} from the frozen baseline. Every page links to the same path on`,
  `the original (${hosts.original}), the static archive (${hosts.static}) and the rebuild (${hosts.d11}).`,
  'Unpublished nodes answer 403 on the original and the rebuild, 404 in the archive (declared for the static target).',
  'The archive column is the static project; its permanent copy is https://static.hobobiker.com (GitHub Pages, which',
  'ignores `?page=N` and serves page 1).',
  '',
  `## Nodes (${manifest.nodes.length})`,
  '',
  '| nid | Type | Title | Status | Compare |',
  '|---|---|---|---|---|',
];
for (const n of [...manifest.nodes].sort((a, b) => a.nid - b.nid)) {
  // The node's alias when it has one (as the sites link it), else node/N.
  const p = n.paths.find((x) => !x.startsWith('node/')) ?? `node/${n.nid}`;
  lines.push(`| ${n.nid} | ${cell(n.type || '(none)')} | ${cell(n.title) || '(untitled)'} | ${n.published ? 'published' : 'unpublished'} | ${links(p)} |`);
}

const routes = index.pages.filter((p) => p.type === 'route');
const kind = (p) => {
  const first = p.split('?')[0].split('/')[0];
  return ['tripinfo_item', 'tripinfo', 'triplog', 'wp', 'audio', 'files', 'blog', 'blog_in_order', 'taxonomy'].includes(first) ? first : 'other pages';
};
const groups = new Map();
for (const r of routes) {
  const k = r.path === '' ? 'other pages' : kind(r.path);
  (groups.get(k) ?? groups.set(k, []).get(k)).push(r.path);
}
lines.push('', `## Other pages (${routes.length})`, '', 'Listings, trip pages, audio pages, files and the home page, as the baseline holds them.', '');
for (const [k, paths] of [...groups].sort((a, b) => b[1].length - a[1].length)) {
  lines.push(`### ${k} (${paths.length})`, '', '| Path | Compare |', '|---|---|');
  for (const p of paths.sort()) {
    lines.push(`| /${cell(p)} | ${links(p)} |`);
  }
  lines.push('');
}

writeFileSync(out, lines.join('\n') + '\n');
console.log(`Wrote ${path.relative(process.cwd(), out)}: ${manifest.nodes.length} nodes, ${routes.length} other pages`);
